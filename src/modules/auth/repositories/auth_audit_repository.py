from datetime import datetime
from typing import Any, Optional
from src.core.database.base_repository import BaseRepository

class MongoAuditRepository(BaseRepository):
    def __init__(self):
        super().__init__("auth_audit_logs")
        self.collection.create_index("action")
        self.collection.create_index("timestamp")

    def log(
        self,
        *,
        action: str,
        auditable_type: Optional[str] = None,
        auditable_id: Optional[str] = None,
        properties: Optional[dict[str, Any]] = None,
        ip_address: Optional[str] = None,
        user_agent: Optional[str] = None,
    ) -> None:
        """
        Logs security/operational events generated by the Auth SDK.
        """
        record = {
            "action": action,
            "auditable_type": auditable_type,
            "auditable_id": auditable_id,
            "properties": properties or {},
            "ip_address": ip_address,
            "user_agent": user_agent,
            "timestamp": datetime.now()
        }
        self.create(record)

auth_audit_repo = MongoAuditRepository()
