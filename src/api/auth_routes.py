@auth_bp.route('/api/user/update-user-avatar', methods=['PUT'])
@require_auth
def update_user_avatar():
    try:
        # 1. Validate File Existence
        if 'avatar' not in request.files:
            return jsonify({"statusCode": 400, "message": "Không tìm thấy file ảnh tải lên. (Key: 'avatar')"}), 400
        
        file = request.files['avatar']
        if file.filename == '':
            return jsonify({"statusCode": 400, "message": "Bạn chưa chọn file nào."}), 400
            
        # 2. Validate File Type — kiểm tra cả extension lẫn MIME type thật
        is_valid, reason = validate_image_file(file, file.filename)
        if not is_valid:
            return jsonify({"statusCode": 400, "message": reason}), 400

        # 3. Check filesize constraints
        file.seek(0, 2)
        if file.tell() > MAX_FILE_SIZE:
             return jsonify({"statusCode": 400, "message": "Kích thước ảnh không được vượt quá 5MB."}), 400
        file.seek(0)
        
        # 4. Upload to Cloudinary
        try:
             # Make sure to configure cloudinary in your app init or environment variables
             upload_result = cloudinary.uploader.upload(
                 file, 
                 folder="user_avatars", # Optional: organize in a folder
                 overwrite=True,
                 resource_type="image"
             )
        except Exception as cloud_err:
             Log.error(f"[Auth] Cloudinary upload failed: {cloud_err}")
             return jsonify({"statusCode": 500, "message": "Lỗi upload ảnh lên Cloudinary server."}), 500
             
        # Extraction secure URL generated by Cloudinary
        avatar_url = upload_result.get('secure_url')
        
        # 5. Save the new URL into User Document (Database)
        # Using the same logic as your other update route
        success = users_repo.update(g.user_id, {
            "avatar_url": avatar_url, 
            "updated_at": datetime.now()
        })
        
        if success:
            Log.info(f"[Auth] Avatar updated successfully on Cloudinary for user: {g.user_id}")
            return jsonify({
                "statusCode": 200, 
                "message": "Cập nhật ảnh đại diện thành công", 
                "data": {
                    "avatar_url": avatar_url
                }
            }), 200
        else:
             Log.warning(f"[Auth] Image uploaded to Cloudinary but failed to update DB for {g.user_id}")
             # Optional: Can delete image from Cloudinary here to save space
             return jsonify({"statusCode": 400, "message": "Đã có lỗi khi lưu dữ liệu vào cơ sở dữ liệu."}), 400
             
    except Exception as e:
        import traceback
        Log.error(f"[Auth] Update avatar failed: {e}\n{traceback.format_exc()}")
        return jsonify({"statusCode": 500, "message": str(e)}), 500

